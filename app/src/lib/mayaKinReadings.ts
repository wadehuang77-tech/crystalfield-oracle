export const MAYA_KIN_READING_VERSION = 'kin-basic-zh-2026-11-05';
export const countMayaReadingCharacters = (text: string) => Array.from(text.replace(/[\p{P}\p{Z}\s]/gu, '')).length;
export interface MayaKinReading {
  kin: number;
  coreTotem: string;
  galacticTone: string;
  toneNumber: number;
  summary: string;
  characterCount: number;
}

export const MAYA_KIN_READINGS: readonly MayaKinReading[] = Array.from({ length: 260 }, (_, index) => {
  const kin = index + 1;
  const seal = getSolarTotemByKin(kin);
  const tone = getToneByKin(kin);
  const summary = sealReflections[seal.number - 1] + toneReflections[tone.number - 1];
  return { kin, coreTotem: seal.nameZh, galacticTone: tone.nameZh, toneNumber: tone.number, summary, characterCount: countMayaReadingCharacters(summary) };
});

export function getMayaKinReading(kin: number): MayaKinReading {
  if (!Number.isInteger(kin) || kin < 1 || kin > 260) throw new RangeError('KIN must be an integer from 1 to 260');
  return MAYA_KIN_READINGS[kin - 1];
}
