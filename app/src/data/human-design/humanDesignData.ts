    'q2-center': `除了當下感受，也可以比較平日、壓力中與獨處後的差異。若一種情緒或疲憊離開某個人後很快減弱，可能是你放大了外界能量；若無論環境都穩定出現，則更接近自身節奏。工作安排、睡眠、飲食與親密互動也會影響身體，不需要把所有狀態都歸因於人類圖。`,
    'q3-throat': `表達是否順暢，往往同時受到時機、安全感、關係權力與身體狀態影響。請觀察自己在誰面前可以不修飾地說話、什麼場合總想搶著證明，以及沉默時是平靜還是害怕。真正的表達不是說得最多，而是內在感受、語言與時機彼此一致，讓聲音既誠實也能被接住。`,
    'q4-direction': `方向感不只來自目標，也藏在環境與身體的回應裡。你可以比較不同空間、工作團隊或關係中的自己：哪裡讓呼吸更深、想法更清楚，哪裡讓你一直懷疑價值？有時不是人生沒有方向，而是所在位置讓內在羅盤受到干擾。先照顧場域與同行的人，再決定遠方。`,
    'q5-relationships': `關係中的能量界線可以從三件事檢查：你能否說出不同意見、拒絕後是否仍被尊重，以及相處後是否還保有自己的感受。靈性連結不等於無條件承擔，深愛也不需要讀懂對方所有情緒。健康關係會允許彼此靠近，也允許各自休息、整理與為自己的選擇負責。`,
    'q6-focus': `接下來不要急著一次解決整個領域，可以先選一個反覆發生的真實情境，記錄事件、身體感受、當時想法與最後選擇。再從現實條件、心理需要、關係互動與能量節奏四個角度看它。人類圖提供的是觀察入口，具體行動仍需要結合你的資源、界線與生活責任。`,
